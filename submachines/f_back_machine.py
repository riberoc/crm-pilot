USE_ZIP = False
USE_COMPILE = False
ZIP_PATH = "submachines.zip"


def boot_f_back_engine():
    print("=" * 60)
    print("         F - B A C K   M A C H I N E   E N G I N E")
    print("=" * 60)
    print(f"[*] Executing submachine sequence stream...")

    if USE_ZIP:
        import zipfile

        if not os.path.exists(ZIP_PATH):
            print(f"[!] Error: Zip archive '{ZIP_PATH}' not found.")
            return

        with zipfile.ZipFile(ZIP_PATH, "r") as zf:
            for sub_id in RAW_SEQ:
                filename = f"submachine_{sub_id}.py"
                try:
                    content = zf.read(filename)
                    if USE_COMPILE:
                        import marshal

                        header_size = 16 if sys.version_info >= (3, 7) else 12
                        code_obj = marshal.loads(content[header_size:])
                        exec(
                            code_obj,
                            {"__name__": "__main__", "sys": sys, "os": os},
                        )
                    else:
                        exec(
                            content.decode("utf-8"),
                            {"__name__": "__main__", "sys": sys, "os": os},
                        )
                except Exception as e:
                    sys.stdout.write("?")
                    sys.stdout.flush()
    else:
        for sub_id in RAW_SEQ:
            filename = f"submachine_{sub_id}.py"
            file_path = os.path.join(".", filename)
            try:
                if USE_COMPILE:
                    import marshal

                    with open(file_path, "rb") as f:
                        raw_pyc = f.read()
                    header_size = 16 if sys.version_info >= (3, 7) else 12
                    code_obj = marshal.loads(raw_pyc[header_size:])
                    exec(
                        code_obj, {"__name__": "__main__", "sys": sys, "os": os}
                    )
                else:
                    with open(file_path, "r", encoding="utf-8") as f:
                        source_code = f.read()
                    exec(
                        source_code,
                        {"__name__": "__main__", "sys": sys, "os": os},
                    )
            except Exception as e:
                sys.stdout.write("?")
                sys.stdout.flush()

    print("\n" + "=" * 60)


if __name__ == "__main__":
    boot_f_back_engine()
