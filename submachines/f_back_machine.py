ZIP_PATH = "submachines.zip"

def boot_f_back_engine():
    print("=" * 60)
    print("          F - B A C K   M A C H I N E   E N G I N E")
    print("=" * 60)
    print(f"[*] Executing submachine bytecode sequence stream from {ZIP_PATH}...")
    
    if not os.path.exists(ZIP_PATH):
        print(f"[!] Error: Zip archive '{ZIP_PATH}' not found.")
        return

    with zipfile.ZipFile(ZIP_PATH, 'r') as zf:
        for sub_id in RAW_SEQ:
            bytecode_name = f"submachine_{sub_id}.pyc"
            try:
                # Read raw .pyc content from zip
                raw_pyc = zf.read(bytecode_name)
                
                # .pyc files contain a header before the marshaled code object.
                # In Python 3.7+, the header is 16 bytes (magic number, bit field, timestamp/hash, size).
                header_size = 16 if sys.version_info >= (3, 7) else 12
                code_obj = marshal.loads(raw_pyc[header_size:])
                
                # Execute in memory with standard module global contexts
                exec(code_obj, {"__name__": "__main__", "sys": sys, "os": os})
            except Exception as e:
                sys.stdout.write("?")
                sys.stdout.flush()

    print("\n" + "=" * 60)

if __name__ == "__main__":
    boot_f_back_engine()
